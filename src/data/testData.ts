/**
 * Tie-breaker bank. Empty by default — the scoring architecture supports
 * isTieBreaker questions, but no forced tie-breaker is shown out of the box.
 * To activate one, add an entry keyed by the sorted pair of tied scenarios,
 * e.g. "A-C", and questionByTiePair() will surface it automatically.
 */
export const tieBreakerQuestions: TestQuestion[] = [];

export function questionByTiePair(a: string, b: string): TestQuestion | null {
  const [x, y] = [a, b].sort();
  return (
    tieBreakerQuestions.find((q) => {
      if (!q.tieBreakerFor) return false;
      const [qa, qb] = [...q.tieBreakerFor].sort();
      return qa === x && qb === y;
    }) ?? null
  );
}
